create or replace function public.sync_spenda_teacher_account(p_teacher_master_id bigint)
returns jsonb language plpgsql security definer set search_path=public as $$
declare m public.teacher_master%rowtype; u uuid;
begin
  if not public.is_spenda_admin() then raise exception 'Akses hanya untuk Admin'; end if;
  select * into m from public.teacher_master where id=p_teacher_master_id;
  if not found then raise exception 'Data guru tidak ditemukan'; end if;
  if nullif(trim(m.email),'') is null then raise exception 'Email guru belum diisi'; end if;
  select id into u from auth.users where lower(trim(email))=lower(trim(m.email)) limit 1;
  if u is null then raise exception 'Akun Supabase Auth dengan email tersebut belum dibuat'; end if;
  update public.teacher_master set user_id=u,updated_at=now() where id=m.id;
  insert into public.teacher_profiles(user_id,school_id,teacher_master_id,full_name,email,nip,no_hp,role,active)
  values(u,m.school_id,m.id,m.full_name,m.email,m.nip,m.no_hp,'teacher',m.active)
  on conflict(user_id) do update set school_id=excluded.school_id,teacher_master_id=excluded.teacher_master_id,full_name=excluded.full_name,email=excluded.email,nip=excluded.nip,no_hp=excluded.no_hp,active=excluded.active,updated_at=now();
  return jsonb_build_object('ok',true,'teacher_master_id',m.id,'user_id',u);
end;$$;
grant execute on function public.sync_spenda_teacher_account(bigint) to authenticated;

create or replace function public.handle_new_spenda_user()
returns trigger language plpgsql security definer set search_path=public as $$
declare m public.teacher_master%rowtype; v_name text;
begin
  select * into m from public.teacher_master where nullif(trim(email),'') is not null and lower(trim(email))=lower(trim(new.email)) and school_id='SMPN2SOYOJAYA' order by id limit 1;
  if found then
    insert into public.teacher_profiles(user_id,school_id,teacher_master_id,full_name,email,nip,no_hp,role,active)
    values(new.id,m.school_id,m.id,m.full_name,m.email,m.nip,m.no_hp,'teacher',m.active)
    on conflict(user_id) do update set teacher_master_id=excluded.teacher_master_id,full_name=excluded.full_name,email=excluded.email,nip=excluded.nip,no_hp=excluded.no_hp,active=excluded.active,updated_at=now();
    update public.teacher_master set user_id=new.id,updated_at=now() where id=m.id;
  else
    v_name:=nullif(trim(coalesce(new.raw_user_meta_data->>'full_name','')),''); if v_name is null then v_name:=split_part(coalesce(new.email,''),'@',1); end if;
    insert into public.teacher_profiles(user_id,school_id,full_name,email,role,active) values(new.id,'SMPN2SOYOJAYA',coalesce(v_name,'Guru'),new.email,'teacher',true) on conflict(user_id) do nothing;
  end if; return new;
end;$$;
drop trigger if exists on_auth_user_created_spenda on auth.users;
create trigger on_auth_user_created_spenda after insert on auth.users for each row execute function public.handle_new_spenda_user();

update public.teacher_profiles p set teacher_master_id=m.id,full_name=m.full_name,email=m.email,nip=m.nip,no_hp=m.no_hp,updated_at=now() from public.teacher_master m where p.teacher_master_id is null and p.user_id=m.user_id;

