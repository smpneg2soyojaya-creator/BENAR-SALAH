-- BANK INSERT: guru harus mempunyai penugasan yang cocok.
drop policy if exists question_banks_insert_teacher on public.question_banks;
create policy question_banks_insert_teacher on public.question_banks for insert to authenticated with check(
  school_id='SMPN2SOYOJAYA' and (
    public.is_spenda_admin() or (
      teacher_user_id=(select auth.uid()) and
      exists(select 1 from public.teacher_profiles p where p.user_id=(select auth.uid()) and p.school_id='SMPN2SOYOJAYA' and p.active=true and lower(trim(p.full_name))=lower(trim(teacher))) and
      exists(select 1 from public.teacher_assignments a where a.teacher_user_id=(select auth.uid()) and a.active=true and lower(trim(a.subject))=lower(trim(subject)) and lower(trim(a.level))=lower(trim(level)) and lower(trim(a.class_name))=lower(trim(class_name)))
    )
  )
);

drop policy if exists question_banks_update_teacher on public.question_banks;
create policy question_banks_update_teacher on public.question_banks for update to authenticated
using(school_id='SMPN2SOYOJAYA' and (teacher_user_id=(select auth.uid()) or public.is_spenda_admin()))
with check(school_id='SMPN2SOYOJAYA' and (public.is_spenda_admin() or (teacher_user_id=(select auth.uid()) and exists(select 1 from public.teacher_assignments a where a.teacher_user_id=(select auth.uid()) and a.active=true and lower(trim(a.subject))=lower(trim(subject)) and lower(trim(a.level))=lower(trim(level)) and lower(trim(a.class_name))=lower(trim(class_name))))));

